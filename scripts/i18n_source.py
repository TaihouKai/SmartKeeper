def nest(flat: dict[str, str]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for key, value in flat.items():
        cur = out
        parts = key.split(".")
        for p in parts[:-1]:
            cur = cur.setdefault(p, {})
        cur[parts[-1]] = value
    return out


def main() -> int:
    for i, lang in enumerate(("zh", "en")):
        data = nest({k: v[i] for k, v in sorted(T.items())})
        path = ROOT / "frontend" / "src" / "i18n" / f"{lang}.json"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(T)} keys")
